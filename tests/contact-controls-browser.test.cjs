const {test}=require('node:test');const assert=require('node:assert/strict');
const {openApp}=require('./browser-helpers.cjs');const {fixture}=require('./helpers.cjs');const {edit,directory}=require('./social-ui-helpers.cjs');
for(const width of [390,1440])test(`contact frequency is optional and delete is accessible at ${width}px`,async t=>{
 const p=await openApp(t,fixture(),{width,height:1000});
 const past=await p.evaluate(()=>JSON.stringify(_state));
 await edit(p,'pold01');await p.locator('#sf-every').fill('');
 await p.getByRole('button',{name:'Guardar cambios',exact:true}).click();
 await p.waitForFunction(()=>!_cfgDraft&&!_cfgFlushPromise&&personById('pold01').every===0);
 await p.reload();await p.waitForFunction(()=>_cfgReady&&_live);
 await p.locator('.nav-btn[data-tab="social"]').click();
 assert.equal(await p.evaluate(()=>personById('pold01').every),0);
 const pill=p.locator('.sd-contact').filter({has:p.getByRole('button',{name:'Editar Ana Existing',exact:true})}).locator('.sd-time-pill');
 assert.equal(await pill.getAttribute('aria-label'),'Sin frecuencia');assert.equal(await pill.textContent(),'Libre');
 await edit(p,'pold01');assert.equal(await p.locator('#sf-every').inputValue(),'');
 await p.locator('#sf-every').fill('7');await p.getByRole('button',{name:'Guardar cambios',exact:true}).click();
 assert.equal(await p.evaluate(()=>personById('pold01').every),7);
 await edit(p,'pold03');
 const del=p.getByRole('button',{name:'Eliminar contacto',exact:true});
 p.once('dialog',dialog=>dialog.dismiss());await del.click();assert.equal(await del.count(),1);
 assert.equal(await p.evaluate(()=>!!personById('pold03')),true);
 p.once('dialog',dialog=>dialog.accept());await del.click();
 await p.waitForFunction(()=>!_cfgDraft&&!_cfgFlushPromise&&personById('pold03')===null);
 assert.equal(await p.locator('.sf-editor').count(),0);
 assert.equal(await p.evaluate(()=>JSON.stringify(_state)),past);
 await p.reload();await p.waitForFunction(()=>_cfgReady&&_live);
 assert.equal(await p.evaluate(()=>personById('pold03')),null);
 assert.equal(await p.evaluate(()=>personWasDeleted('pold03')),true);
 assert.equal(await p.evaluate(()=>JSON.stringify(_state)),past);
 await directory(p);await p.locator('.sf-directory-actions').getByRole('button',{name:'+ Persona',exact:true}).click();
 await p.locator('#sf-name').fill('Synthetic no frequency');
 assert.equal(await p.locator('#sf-every').inputValue(),'');
 await p.getByRole('button',{name:'Guardar persona',exact:true}).click();
 await p.waitForFunction(()=>!_cfgDraft&&!_cfgFlushPromise&&peopleList().some(p=>p.name==='Synthetic no frequency'&&p.every===0));
 await p.reload();await p.waitForFunction(()=>_cfgReady&&_live);
 assert.equal(await p.evaluate(()=>peopleList().find(p=>p.name==='Synthetic no frequency').every),0);
 assert.equal(await p.evaluate(()=>JSON.stringify(_state)),past);
 assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
});
